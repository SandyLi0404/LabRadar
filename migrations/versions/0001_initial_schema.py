"""Initial schema and canonical research areas.

The tables are created from the declarative metadata rather than transcribed by
hand. Every table and index copied out manually would be a second source of
truth to keep in step with the models; creating them from metadata means the
first migration cannot drift. Later revisions are autogenerated in the normal
way, since autogenerate diffs the models against the live database and does not
care how the tables first appeared.

This revision squashes the earlier 0001-0006 history. A database created before
the squash records revision 0006, which no longer exists: recreate it
(``docker compose down -v``) and re-run ``labradar run-all``.

Revision ID: 0001
Revises:
"""

from __future__ import annotations

import sqlalchemy as sa
from alembic import op

from labradar.db.models import Base
from labradar.sources.columbia import RESEARCH_AREAS, area_url

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None


def upgrade() -> None:
    bind = op.get_bind()
    Base.metadata.create_all(bind=bind)

    # The eleven areas are a fixed department taxonomy, so they are reference
    # data rather than something the scrape discovers.
    research_area = sa.table(
        "research_area",
        sa.column("slug", sa.String),
        sa.column("name", sa.String),
        sa.column("url", sa.String),
    )
    op.bulk_insert(
        research_area,
        [
            {"slug": slug, "name": name, "url": area_url(slug)}
            for slug, name in RESEARCH_AREAS.items()
        ],
    )


